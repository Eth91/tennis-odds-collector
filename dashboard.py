            for f in flags:
                gk = f.get("game") or f["pitcher"]
                if gk not in groups:
                    groups[gk] = []
                    order.append(gk)
                groups[gk].append(f)
            out = ""
            for gk in order:
                fl = groups[gk]
                home_name, _, start = (gk or "||").partition("|")
