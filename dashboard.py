def _probables_today():
    """{pitcher_lower: [away_bool, opp_full_name]} from MLB statsapi probables — the AUTHORITATIVE
    home/away + full opponent name (which joins _team_hit). FanDuel dropped the '(pitcher)' annotation
    and abbreviated the cities in its event string on 2026-07-21 ('TB Rays @ TOR Blue Jays'), which
    broke the old event-string parse and blanked the whole board. Memoized per-process; persisted to
    a daily file so a transient statsapi blip falls back to today's cache instead of going dark."""
    today = dt.date.today().isoformat()
    if _PROB_MEMO.get("date") == today:
        return _PROB_MEMO["map"]
    m = {}
    try:
        from mlb import data as _MD
        for g in _MD.probables(today):
            nm = (g.get("pitcher") or "").lower()
            if nm:
                m[nm] = [bool(g.get("away")), g.get("opp") or ""]
    except Exception:
        m = {}
    if m:                                              # fresh -> persist for a later blip
        try:
            _MLB_PROB.write_text(json.dumps({"date": today, "map": m}))
        except OSError:
            pass
    else:                                              # statsapi blip -> reuse today's cached file
        try:
            c = json.loads(_MLB_PROB.read_text())
            if c.get("date") == today:
                m = c.get("map", {})
        except (ValueError, OSError):
            m = {}
    _PROB_MEMO.clear()
    _PROB_MEMO.update(date=today, map=m)
    return m


def _mlb_matchup(event, player):
    """(is_away, opponent_full_name) for a starting pitcher, from MLB statsapi probables. The FD
    `event` string is no longer parsed (FD dropped pitchers + abbreviated cities 2026-07-21) — kept
    in the signature for callers. Exact name match, then a last-name fallback, else (None, '')."""
    pm = _probables_today()
    v = pm.get((player or "").lower())
    if not v and player:
        ln = player.split()[-1].lower()
        for name, val in pm.items():
            if ln and ln in name:
                v = val
                break
    return (bool(v[0]), v[1]) if v else (None, "")


def _lag_s(cat, lead):
    """Seconds `cat` trails `lead` (both ISO collected_at strings). Unparseable/missing -> huge, so a
    quote we can't date is treated as dead rather than silently shopped into."""
    if not cat or not lead:
        return 1 << 30
    try:
        return max(0.0, (dt.datetime.fromisoformat(lead) - dt.datetime.fromisoformat(cat)).total_seconds())
    except ValueError:
        return 1 << 30


def _mlb_plays(now=None):
    """Today's MLB pitcher-prop plays at the BEST soft book (FD/DK/BetMGM): outs-under ≤16.5
    (the away+contact edge) + K-over ≥6.5. Per pitcher+market pick the best LINE (under: highest;
    over: lowest), then the best odds; matchup + home/away parsed from the FD event string."""
    if not FD_PROPS.exists():
        return []
    try:
        con = sqlite3.connect(f"file:{FD_PROPS}?mode=ro", uri=True)
        rows = con.execute(
            "SELECT book, player, event, stat, line, side, odds, collected_at FROM fd_lines "
            "WHERE sport='mlb' AND stat IN ('outs','strikeouts') "
            "AND collected_at > datetime('now','-18 hours')").fetchall()
        con.close()
    except sqlite3.Error:
        return []
    latest, ev_by = {}, {}                             # freshest odds per (book,player,stat,line,side)
    for bk, pl, ev, stat, line, side, odds, cat in rows:
        if odds is None or line is None or side is None:
            continue
        k = (bk or "fd", pl, stat, round(float(line), 1), side)
        if k not in latest or cat > latest[k][1]:
            latest[k] = (float(odds), cat)
        ev_by[(pl, stat)] = ev
    # a pitcher's ladder -> the MAIN line only (2-sided, over-odds nearest even) so we never bet an
    # alt rung (e.g. over 6.5 @ +560 on an opener). Then line-shop that main line across books.
    ladder = {}                                        # (book,player,stat) -> {line: {side: odds}}
    for (bk, pl, stat, line, side), (odds, _c) in latest.items():
        ladder.setdefault((bk, pl, stat), {}).setdefault(line, {})[side] = odds
    # ── LIVE-QUOTE GATE (2026-07-24). The 18h window above exists so a play stays on the board all
    # day, but it has a price-integrity cost: a book that PULLED a market (scratch, late injury,
    # suspended) keeps its last quote for 18h — and if that dead price is the best, we line-shop INTO
    # it and advertise a number nobody can actually bet. Per pitcher, a book is shoppable only if its
    # freshest quote is within STALE_LAG of the freshest quote ANY book has for him: loose enough to
    # absorb the fd-vs-dk collection-cadence gap, tight enough to drop a book that stopped quoting.
    STALE_LAG = 45 * 60
    seen_at = {}                                        # (book,player,stat) -> freshest collected_at
    for (bk, pl, stat, _ln, _sd), (_o, cat) in latest.items():
        k = (bk, pl, stat)
        if k not in seen_at or cat > seen_at[k]:
            seen_at[k] = cat
    lead_at = {}                                        # (player,stat) -> freshest across ALL books
    for (bk, pl, stat), cat in seen_at.items():
        if (pl, stat) not in lead_at or cat > lead_at[(pl, stat)]:
            lead_at[(pl, stat)] = cat
    mains = {}                                          # (player,stat) -> [(book, line, over, under)]
    for (bk, pl, stat), lines in ladder.items():
        if _lag_s(seen_at.get((bk, pl, stat)), lead_at.get((pl, stat))) > STALE_LAG:
            continue                                     # book went dark on him — its price is dead
        two = {ln: v for ln, v in lines.items() if "over" in v and "under" in v} or lines
        main = min(two, key=lambda ln: abs((two[ln].get("over") or two[ln].get("under") or 9) - 1.95))
        mains.setdefault((pl, stat), []).append((bk, main, two[main].get("over"), two[main].get("under")))
    hit = _team_hit()
    ppa_low = _ppa_low(hit)
    plays = []
    for (pl, stat), offs in mains.items():
        if stat != "outs":
            continue                          # K-over pulled 2026-07-21 (weak +3% & no stack — audit)
        away, opp = _mlb_matchup(ev_by.get((pl, stat), ""), pl)
        # base edge: AWAY starter vs a CONTACT offense (+25% ROI). Home loses; away+whiff marginal.
        oh = hit.get((opp or "").lower(), {})
        oppk = oh.get("k")
        if not away:
            continue
        if hit and oppk is not None and oppk >= CONTACT_MAX:
            continue
        cands = [(bk, ln, uo) for bk, ln, oo, uo in offs if uo and ln <= OUTS_UNDER_MAX]
        if not cands:
            continue
        cands.sort(key=lambda x: (x[1], x[2]), reverse=True)          # highest main line, then best odds
        bk, line, odds = cands[0]
        # THE MODEL v3 — ROUTE-A ONLY (2026-07-23, user: "B is contradictive, scratch it"). Was
        # away+contact AND (low-patience opp [route B] OR line > recent-5 median outs [route A]).
        # ROUTE B IS DROPPED, and plays where BOTH fire are scratched too, because B is backwards:
        # an impatient / weak-on-base offense means FEWER pitches per PA and FEWER baserunners, so the
        # starter goes DEEPER — that argues AGAINST an outs-under, not for it. B's backtest was also
        # leak-flattered (season-long team stats classify with hindsight) and it has essentially no
        # real-line support (1 FanDuel bet). Evidence: A-only 17-4 (81%, +43.8% ROI) and 5-0 at FD;
        # BOTH-fire 4-4 overall and 1-2 at FD; B-only 9-1 but that's ~all in-sample Pinnacle.
        # Route A survives because its mechanism is sound (the book lined him ABOVE his own recent
        # form = a market-vs-form edge) and it's point-in-time clean (prior starts only).
        # Costs ~46% of volume (39 -> 21 bets) but lifts ROI +39.2% -> +43.8%. k_paper keeps logging
        # EVERY outs-under regardless, so B stays scoreable and this stays reversible.
        oppp = oh.get("ppa")
        r5 = _pitcher_r5(pl)
        route_a = bool(r5 is not None and line > r5)
        route_b = bool(oppp is not None and oppp < ppa_low)
        premium = route_a and not route_b
        if not premium:
            continue                                     # only the model's plays
        # PRICE-SHOP THE RUNG (edge already decided on the validated ≤16.5 line above). Take a HIGHER
        # under line ONLY if some book offers it at odds >= our pick — a safer line at no-worse price
        # strictly dominates (free lunch on a stale/mispriced book). We deliberately do NOT pay extra
        # juice to climb a rung: that EV-chase is unvalidated (no historical alt-rung data yet) and a
        # from-scratch outs-distribution model can't reproduce our +44% selection edge, so it can't be
        # trusted to price a 17.5. Dominance only. Rasmussen 17.5 @ -138 vs 16.5 @ +110 -> keeps 16.5.
        base = line
        ups = [(b, ln, uo) for b, ln, oo, uo in offs if uo and ln > base and uo >= odds]
        if ups:
            ups.sort(key=lambda x: (x[2], x[1]), reverse=True)        # best price, then highest line
            bk, line, odds = ups[0]
        # what the OTHER books had on the same rung — rendered next to the pick so the shop is
        # visible (and auditable) instead of the board just asserting one book's number.
        alt = sorted([(b, uo) for b, ln, oo, uo in offs
                      if uo and abs(ln - line) < .01 and b != bk], key=lambda x: -x[1])
        plays.append({"pitcher": pl, "market": "outs", "side": "under", "line": line, "odds": odds,
                      "book": bk, "opp": opp, "away": away, "premium": True, "base_line": base,
                      "alt": alt, "quoted_at": seen_at.get((bk, pl, stat)),
                      "books_seen": len({b for b, _l, _o, _u in offs})})
    plays.sort(key=lambda p: p["pitcher"])
    return plays[:16]


def _mlb_health():
    """Tell a BROKEN pipeline apart from a genuinely quiet slate so an empty board is never silent
    again (2026-07-21: an FD event-format change blanked the board behind a calm 'no plays' card).
    Returns {"ok", "reason"}. Trips ONLY on unambiguous breaks — lines are flowing but the matchup/
    stats inputs don't resolve — never on a real off-day (too few lines -> stays quiet)."""
    try:
        if not FD_PROPS.exists():
            return {"ok": True, "reason": ""}
        con = sqlite3.connect(f"file:{FD_PROPS}?mode=ro", uri=True)
        pitchers = [r[0] for r in con.execute(
            "SELECT DISTINCT player FROM fd_lines WHERE sport='mlb' AND stat='outs' "
            "AND collected_at > datetime('now','-18 hours')").fetchall()]
        con.close()
    except sqlite3.Error:
        return {"ok": True, "reason": ""}
    n = len(pitchers)
    if n < 5:                                    # too few lines to judge (early / off-day) — not an alarm
        return {"ok": True, "reason": ""}
    if len(_team_hit()) < 20:                     # team K%/patience feed down -> contact+premium degraded
        return {"ok": False, "reason": "team-stats feed down"}
    if not _probables_today():                    # no matchup source (statsapi down AND no cache)
        return {"ok": False, "reason": "no matchup source (statsapi probables empty)"}
    resolved = sum(1 for p in pitchers if _mlb_matchup("", p)[0] is not None)
    if resolved == 0:                             # THE 2026-07-21 signature: lines flow, nothing resolves
        return {"ok": False, "reason": f"0/{n} matchups resolve — book format change?"}
    # PARTIAL break judged against CONFIRMED starters, not all lined pitchers (2026-07-23 fix): books
    # (esp. DraftKings) post speculative + NEXT-DAY outs lines hours ahead of statsapi confirming
    # starters, so `n` is inflated early (e.g. 47 lines vs ~10 confirmed) and comparing `resolved` to
    # it tripped the red banner every morning (cry-wolf). A confirmed starter that's lined DOES resolve
    # (both come from the same probables map); unconfirmed/next-day lines simply don't resolve yet =
    # NOT a break. So alarm only when plenty of starters ARE confirmed yet few resolve (name-join break).
    np_ = len(_probables_today())
    if np_ >= 5 and resolved < np_ * 0.5:
        return {"ok": False, "reason": f"only {resolved}/{np_} confirmed starters resolve"}
    return {"ok": True, "reason": ""}


