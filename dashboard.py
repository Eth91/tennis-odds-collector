def _considered_html(rows):
    """Plays the model flagged and then REJECTED for this slate — shown as context, never as bets.

    A rejected play used to leave no trace on any surface a human reads: the correlation cap deletes
    the losing leg before the ledger write, so DiLeo (2026-07-31) beat Carleton on every signal and
    then simply was not there. Surfacing them makes selection mistakes visible the same night
    instead of two weeks later.

    Fully guarded: any failure returns "" so this can never blank the board."""
    try:
        import csv as _csv
        from collections import OrderedDict
        dates = {r.get("pred_date") for r in rows if r.get("pred_date")}
        if not dates:
            return ""
        seen = OrderedDict()

        # 1. losers of a correlation-cap pool
        capf = HERE / "wnba_capped_legs.csv"
        if capf.exists():
            with open(capf) as fh:
                for c in _csv.reader(fh):
                    if len(c) < 9 or c[0] not in dates:
                        continue
                    try:
                        line = float(c[5])
                    except ValueError:
                        continue
                    dm = None
                    try:
                        dm = float(c[8])
                    except (ValueError, IndexError):
                        pass
                    seen[(c[0], c[3], c[4], line)] = {
                        "date": c[0], "team": c[1], "player": c[3], "stat": c[4],
                        "line": line, "odds": c[6], "d_min": dm,
                        "why": "lost the %s pool to %s" % (c[4], _short(c[2]))}

        # 2. plays that lost a TOP-2 slot
        try:
            import wnba_slip as _S
            _ov = [r for r in rows if (r.get("side") or "over") == "over"]
            _, _dropped = _S.current_selection(_ov)
            for r, why in _dropped or []:
                k = (r.get("pred_date"), r.get("player"), r.get("stat"), r.get("line"))
                if k in seen:
                    continue
                seen[k] = {"date": r.get("pred_date"), "team": r.get("team"),
                           "player": r.get("player"), "stat": r.get("stat"),
                           "line": r.get("line"), "odds": r.get("odds"),
                           "d_min": r.get("d_min"), "why": why}
        except Exception:                                            # noqa: BLE001
            pass

        # A play we are CURRENTLY betting must never render as "not bet". wnba_capped_legs.csv is
        # append-only, so a decision reversed later in the day (the correlation-cap fix flipping
        # Carleton/DiLeo) leaves a stale row that would otherwise contradict the card.
        _sel_now = set()
        try:
            import wnba_slip as _S2
            _k, _ = _S2.current_selection([r for r in rows
                                           if (r.get("side") or "over") == "over"])
            _sel_now = {(r.get("player"), r.get("stat")) for r in _k}
        except Exception:                                            # noqa: BLE001
            pass
        for _k2 in [k for k in seen if (seen[k].get("player"), seen[k].get("stat")) in _sel_now]:
            seen.pop(_k2, None)

        if not seen:
            return ""
        out = ""
        for v in list(seen.values())[:12]:
            dm = v.get("d_min")
            band = ("in the 3-8 band" if (dm is not None and 3 <= dm <= 8)
                    else ("min %+g" % dm if dm is not None else ""))
            ln = v.get("line")
            out += ('<div class="ttbet"><span class="pind o">O</span>'
                    '<span class="ttbln">%s</span>'
                    '<div class="ttbmid"><div class="ttbnm"><b>%s</b> %s</div>'
                    '<div class="ttbsb">%s%s</div></div></div>'
                    % (("%g" % ln) if ln is not None else "-",
                       html.escape(str(v.get("player") or "?")),
                       html.escape(STAT.get(v.get("stat"), str(v.get("stat") or ""))),
                       html.escape(str(v.get("why") or "")),
                       (" · " + band) if band else ""))
        return ('<div class="card"><h3 class="ttlg">Also considered · NOT BET</h3>' + out +
                '<div class="ttfoot">Rejected by the selection rules. No stake, no alert.'
                '</div></div>')
    except Exception:                                                # noqa: BLE001
        return ""


def _ladders_html(rows):
    """🪜 Laddered plays pulled into their own section so they're easy to find: each player-stat with
    2+ rungs, showing every rung's line/odds and the user's ladder stake (1u base + declining rungs)."""
    try:
        import wnba_slip as S
        from collections import defaultdict
        overs = [r for r in rows if (r.get("side") or "over") == "over"]
        overs = S.current_selection(overs)[0]            # top-2 disjoint per team-game (matches tracked record)
        sm = S.ladder_stake_map(overs)
        groups = defaultdict(list)
        for r in overs:
            groups[(r.get("pred_date"), r.get("player"), r.get("stat"))].append(r)
        ladders = [(k, rr) for k, rr in groups.items() if len(rr) > 1]
        if not ladders:
            return ""
        ladders.sort(key=lambda kr: -max((x.get("ev") or 0) for x in kr[1]))
        cards = ""
        for (d, player, stat), rr in ladders:
            rr = sorted(rr, key=lambda x: x["line"])
            lns = [x["line"] for x in rr]
            tot = sum(sm.get((d, player, stat, x["line"]), 0.0) for x in rr)
            rungs = ""
            for x in rr:
                bpr = _book_prices(x)
                dec = bpr[0][1] if bpr else float(x["odds"])
                stake = sm.get((d, player, stat, x["line"]), 0.0)
                pv = ' <span class="lv">✓</span>' if x.get("played") else ""
                rungs += (f'<div class="lrung"><b>o{x["line"]:g}</b>'
                          f'<span class="lro">{_am(dec)}</span>'
                          f'<span class="lst">{stake:g}u</span>{pv}</div>')
            cards += (f'<div class="ladder"><div class="lhd">'
                      f'<span class="lname">{html.escape(_short(player))}</span>'
                      f'<span class="lstat">{S.STAT_LABEL.get(stat, stat)}</span>'
                      f'<span class="lrange">o{lns[0]:g}–{lns[-1]:g}</span>'
                      f'<span class="lsp"></span><span class="ltot">{tot:g}u <span>total</span></span></div>'
                      f'<div class="lrungs">{rungs}</div></div>')
        return ('<div class="ladders"><div class="op-title">Ladders'
                '</div>'
                f'{cards}</div>')
    except Exception:
        return ""


def build():
    now = dt.datetime.now(dt.timezone.utc).astimezone(MT)   # MT for the displayed clock only
    # the BOARD's slate day is ET (matches pred_date the scanner stamps) — using MT hid plays during
    # the ET-night / MT-evening window (a bet stamped ET-tomorrow was invisible on the MT-today board).
    today = dt.datetime.now(ET).date().isoformat()        # ET slate date the scanner stamps
    rows, (w, l, u, pend) = _load(today)
    pend_all = list(rows)          # EVERY open flag (each one pinged the phone) — coherence source
    # board shows the TOP-2 DISJOINT plays per team-game (matches the tracked record + ladders +
    # parlays): the play cards recommend exactly what to bet. Ledger keeps all. Overflow -> strip.
    favs = set()
    try:
        import wnba_slip as _SLB
        _ov = [r for r in rows if (r.get("side") or "over") == "over"]
        favs = _fav_keys(_ov)                            # favorite over ALL flagged overs (market order)
        _keep = {(r["pred_date"], r["player"], r["stat"], r["line"]) for r in _SLB.current_selection(_ov)[0]}
        rows = [r for r in rows if (r.get("side") or "over") != "over"
                or (r["pred_date"], r["player"], r["stat"], r["line"]) in _keep]
    except Exception:
        pass
    tips = _tip_times()
    for r in rows:
        r["_tier"] = _tier(r, (r.get("pred_date"), r.get("player"), r.get("stat")) in favs)
    # GROUP BY DAY > GAME > player — the board shows tonight's plays AND any already-posted
    # next-day plays (keyed by date so the same matchup on back-to-back days stays separate).
    by_player = defaultdict(list)
    for r in rows:
        by_player[(r.get("pred_date"), r["player"])].append(r)
    games = defaultdict(list)                              # {(date, teams-pair): [(player, rows)]}
    for (pd, player), prs in by_player.items():
        team = (prs[0].get("team") or "").upper()
        opp = (prs[0].get("opp") or "").upper()
        games[(pd, tuple(sorted((team, opp))))].append((player, prs))

    # ── archetype-blended ranking + per-game cap (user: fewer plays, surface my favorites) ──
    # Raw EV buried the plays he trusts (Thomas RA-under ranked last, Burrell volume-over unscored),
    # so his 3 validated archetypes get a boost to lead; everything else fills remaining slots by EV.
    ARCHE_BOOST, EXPAND_BAR, CAP = 0.15, 0.20, 3

    def _arche(r):
        side, stat = (r.get("side") or "over"), (r.get("stat") or "")
        if side == "over" and stat == "points" and (r.get("basis") == "volume" or (r.get("d_fga") or 0) >= 2):
            return ARCHE_BOOST                            # volume-over on a role player (Burrell)
        if side == "under" and stat in ("rebounds", "assists", "reb_ast"):
            return ARCHE_BOOST                            # reduced-role reb/ast under (Thomas)
        if side == "over" and stat == "rebounds" and (r.get("d_min") or 0) >= 2:
            return ARCHE_BOOST                            # role-player rebound over, vacated frontcourt (Bonner)
        return 0.0

    def _score(r):
        # EV capped at 0.25 for RANKING (calibration 2026-07-17: fatter claims delivered 50%) —
        # keeps a phantom edge from outranking proven plays on the cards; display stays raw.
        # NOTE: a +0.10 multi-out boost lived here for ~2h and was REMOVED same day — the 88%
        # proxy-line cell did NOT survive real lines (our graded bets: 2+ out 56% vs 1 out 60%;
        # fd_lines replay: one qualifying slate). The '2★ out' badge stays as pure information.
        return min(r.get("ev") or 0, 0.25) + _arche(r)

    def _pscore(prs):
        return max(_score(r) for r in prs)

    # cap each game to the top-CAP PLAY-GROUPS (player × stat × side, so an under's rungs or an overs
    # ladder count as ONE play), expandable for genuinely strong extras. Display-only — the ledger
    # keeps every flag; we just stop flooding the board with marginal legs.
    for gk in list(games.keys()):
        pg = defaultdict(list)
        for pl, prs in games[gk]:
            for r in prs:
                pg[(pl, r["stat"], (r.get("side") or "over"))].append(r)
        ranked = sorted(pg.items(), key=lambda kv: -max(_score(x) for x in kv[1]))
        keep = ranked[:CAP] + [x for x in ranked[CAP:] if max(_score(r) for r in x[1]) >= EXPAND_BAR]
        byp = defaultdict(list)
        for (pl, _st, _sd), rungs in keep:
            byp[pl].extend(rungs)
        games[gk] = sorted(byp.items(), key=lambda kv: -_pscore(kv[1]))

    # ── coherence strip (2026-07-16 user: "notifications for players who aren't on the dashboard") ──
    # The cards deliberately curate (favorite-only cascade + top-3/game), but EVERY open flag pinged
    # the phone — so anything curated off the cards/ladders renders in a compact "also flagged" strip.
    # Rule: if it pings, it's on the board; shadows don't ping.
