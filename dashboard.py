def _bars(r, meters=""):
    """The expanded card detail. CUPERTINO-DW: a flat vertical stack of labelled sections —
    confidence, reasoning, same-lineup history, recent games — separated by one hairline each.

    Emits dw-* class names deliberately. The previous drawer accumulated rules across several
    passes that fought each other on specificity; a fresh namespace means none of them can match
    this markup, so its spacing is defined in exactly one place.
    """
    def sec(label, inner):
        """A section, or nothing at all. An absent block must not leave an orphan label or a
        trailing rule behind it — that was half of what made the old spacing look arbitrary."""
        if not inner:
            return ""
        lab = f'<div class="dw-l">{label}</div>' if label else ""
        return f'<div class="dw-s">{lab}{inner}</div>'

    # No label on the meters or the reasoning: both are self-describing ("when they sit 2/2 over"
    # needs no CONFIDENCE header above it) and a label costs a full row. Labels are kept only where
    # the block would otherwise be ambiguous.
    parts = [sec("", meters),
             sec("", f'<div class="dw-p">{_reasoning(r)}</div>'),
             sec("Same-lineup history", _regime_html(r))]

    s_ = _samples(r)
    if s_:
        s_ = list(reversed(s_))                        # newest-first -> oldest on the left
        line = float(r["line"])
        side = (r.get("side") if hasattr(r, "get") else r["side"]) or "over"
        vals = [x[0] for x in s_]
        # two scales, so the gray minutes bar always reads taller than the coloured stat bar
        mx = max(max(vals), line) * 1.62 or 1
        onside = (lambda v: v > line) if side == "over" else (lambda v: v < line)
        hits = sum(1 for v in vals if onside(v))
        cols = ""
        for x in s_:
            v = x[0]
            mn = x[2] if len(x) > 2 else 0
            cols += (f'<div class="dw-col">'
                     f'<div class="dw-min" style="height:{min(mn / 42 * 100, 97):.0f}%"></div>'
                     f'<div class="dw-bar {"on" if onside(v) else "off"}" '
                     f'style="height:{v / mx * 100:.1f}%"><span>{v:g}</span></div></div>')
        opps = "".join(f'<span>{html.escape(str(o) or "")}</span>' for _, o, *_ in s_)
        chart = (f'<div class="dw-chart">'
                 f'<div class="dw-line" style="bottom:{line / mx * 100:.1f}%"><span>{line:g}</span></div>'
                 f'{cols}</div><div class="dw-opps">{opps}</div>'
                 f'<div class="dw-note">{hits}/{len(s_)} {side} {line:g}</div>')
        parts.append(sec("Recent games", chart))
    else:
        parts.append(sec("Recent games", '<div class="dw-p">No game data.</div>'))

    return f'<div class="bars"><div class="dw">{"".join(p for p in parts if p)}</div></div>'

def _splits(r):
    """The player's OVER/UNDER hit rate AT THIS LINE over recent windows — L5 / L10 / season / vs
    this opponent (H2H) — from the live game log. Returns {'l5':(hits,n), ...} or None. This is the
    props.cash time-split heatmap: raw recent form at the exact number, beside our ROLE edge."""
    pid = NAME2ID.get(r["player"])
    key = STATKEY.get(r["stat"])
    if not pid or not key:
        return None
    log = [g for g in _glog(pid) if (g.get("min") or 0) > 0]      # played games, newest-first
    if not log:
        return None
    line = float(r["line"])
    side = (r.get("side") if hasattr(r, "get") else r["side"]) or "over"

    def hr(games):
        vals = [g.get(key) for g in games if g.get(key) is not None]
        if not vals:
            return None
        return sum(1 for v in vals if (v > line) == (side == "over")), len(vals)

    opp = (r.get("opp") or "").upper()
    h2h = hr([g for g in log if (g.get("matchup") or "").upper() == opp]) if opp else None
    return {"l5": hr(log[:5]), "l10": hr(log[:10]), "szn": hr(log), "h2h": h2h}


def _hrcell(lbl, hr, role=False):
    """One heatmap cell: hit% at the line, W/N underneath. The TINT lives on the cell (faint green/
    red wash, desaturated value) — not glowing text — so the grid reads as a heatmap, and saturated
    green stays reserved for the model edge. `role` marks our injury-context cell (blue label)."""
    base = "gc r" if role else "gc"
    if not hr or not hr[1]:
        return (f'<div class="{base}"><span class="gcl">{lbl}</span>'
                f'<span class="gcv dim">—</span><span class="gcs">&nbsp;</span></div>')
    pct = hr[0] / hr[1] * 100
    cls = " hot" if pct >= 65 else (" cold" if pct <= 35 else "")   # hot/cold: no collision with .b bars
    return (f'<div class="{base}{cls}"><span class="gcl">{lbl}</span>'
            f'<span class="gcv">{pct:.0f}%</span><span class="gcs">{hr[0]}/{hr[1]}</span></div>')


def _book_prices(r):
    """[(book, dec_odds)] for THIS prop's bet side, BEST price first, from the last day of fd_lines
    (FanDuel + DraftKings live in the same table). Reads the freshest lines DB (resilient to a
    dropped collect-odds cron). Lets the card show WHERE the best number is. [] if unreachable."""
    import wnba_props_db as PDB
    db = PDB.props_db()
    if not Path(db).exists():
        return []
    side = (r.get("side") if hasattr(r, "get") else r["side"]) or "over"
    try:
        con = sqlite3.connect(f"file:{db}?mode=ro", uri=True)
        rows = con.execute(
            "SELECT COALESCE(book,'fd') b, odds, collected_at FROM fd_lines WHERE sport='wnba' "
            "AND player=? AND stat=? AND ROUND(line,1)=? AND side=? "
            "AND collected_at > datetime('now','-1 day')",
            (r["player"], r["stat"], round(float(r["line"]), 1), side)).fetchall()
        con.close()
    except Exception:
        return []
    if not rows:
        return []
    # CURRENT snapshot only: the LATEST quote per book, and drop a book whose newest quote for this
    # rung is stale (>FRESH_MIN behind the newest) — never MAX-over-time, which showed an old, more
    # generous price as the live 'best price' (the same bug fixed in posted_props).
    newest = max(ca for _, _, ca in rows)
    try:
        cutoff = (dt.datetime.fromisoformat(newest) - dt.timedelta(minutes=FRESH_MIN)).isoformat()
    except ValueError:
        cutoff = ""
    latest = {}                                        # book -> (collected_at, odds)
    for b, o, ca in rows:
        if o is None or ca < cutoff:
            continue
        if b not in latest or ca > latest[b][0]:
            latest[b] = (ca, o)
    return sorted([(b, o) for b, (ca, o) in latest.items()], key=lambda x: -x[1])


def _cu_status(r):
    """Lineup status as an iOS pill. Real values only — the logger writes exactly these four."""
    return {"confirmed": ("Starting", "ok"), "likely": ("Likely", "mid"),
            "bench": ("Bench", "pp"), "projected": ("TBD", "no")}.get(
                r.get("confidence") or "projected", ("TBD", "no"))


def _cu_conf(r):
    """The card-face confidence bar. This is the model's OWN primary meter promoted out of the
    drawer, never a new number: volume rows show proj_hit, role rows show the when-they-sit record.
    Returns (pct, label, good) or None when the model has neither — the card then shows an em-dash
    rather than inventing a figure."""
    if r.get("basis") == "volume" and r.get("proj_hit"):
        p = r["proj_hit"] * 100
        # NOT the percentage again — .cu-pc already prints it. Label with what the model produced.
        ea = r.get("elev_avg")
        return p, (f"proj {ea:g}" if ea is not None else "volume model"), p >= 60
    rec = _raw_record(r)
    if rec and rec[1]:
        p = rec[0] / rec[1] * 100
        return p, f'{rec[0]}/{rec[1]} when out', p >= 60
    sp = _splits(r) or {}
    l10 = sp.get("l10")
    if l10 and l10[1]:
        p = l10[0] / l10[1] * 100
        return p, f'{l10[0]}/{l10[1]} last 10', p >= 60
    return None


