    line = float(r["line"])
    stat = STAT.get(r["stat"], r["stat"])
    avg = rg["comp_avg"]
    names = ", ".join(rg.get("sig_names", [])[:3]) or "key players"
    # the IN-config that defines a TRUE comp — who's on the floor caps usage as much as who's out
